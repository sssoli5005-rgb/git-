function normalize(value: string): string {
  return value
    .toLocaleLowerCase()
    .normalize("NFKC")
    .replace(/[\u064B-\u065F\u0670]/gu, "")
    .replace(/[أإآ]/gu, "ا")
    .replace(/ى/gu, "ي")
    .replace(/[ًٌٍَُِّْـ]/gu, "")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/gu, " ")
    .trim();
}

const FOLLOW_UP_PATTERN =
  /^(?:(?:طب|طيب|تمام|ماشي|حلو|يعني)\s*)?(?:اعمل ايه|اتصرف ازاي|ازاي ارد|ارد اقول ايه|اكمل ازاي|والحل ايه|ايه الخطوه الجايه|ممكن توضح|اشرح اكتر|كمل|كملي|كمللي)$/u;
const CONTEXTUAL_REFERENCE_PATTERN =
  /(?:^|\s)(?:هل\s+ده|ده\s+(?:يثبت|معناه|يعني|يدل|يفسر|سببه)|دي\s+(?:تثبت|معناها|تعني|تدل|تفسر)|المعلومة\s+(?:دي|ده)|الكلام\s+(?:ده|دي)|في\s+(?:المثال|الحالة)\s+(?:ده|دي)|does\s+this\s+(?:mean|prove)|does\s+that\s+(?:mean|prove)|what\s+does\s+that\s+mean)(?=\s|$)/u;

function isContextualFollowUp(latest: string, previous: string): boolean {
  if (!previous) return false;
  const normalizedLatest = normalize(latest);
  return (
    FOLLOW_UP_PATTERN.test(normalizedLatest) ||
    CONTEXTUAL_REFERENCE_PATTERN.test(normalizedLatest)
  );
}

function getRelevantEntries(
  messages: Array<{ role: "user" | "assistant"; content: string }>,
  limit = 4,
): KnowledgeEntry[] {
  const userMessages = messages.filter((message) => message.role === "user");
  const latest = userMessages.at(-1)?.content ?? "";
  const previous = userMessages.at(-2)?.content ?? "";
  const sourceRequest = isSourceRequest(latest);
  const query = normalize(
    isContextualFollowUp(latest, previous) || sourceRequest
      ? `${previous} ${latest}`
      : latest,
  );
  if (!query) return [];

  if (query.includes("الهيروغليفية المصرية")) {
    const exactEntry = KNOWLEDGE.find((entry) => entry.id === "egyptian-hieroglyphic-basics");
    return exactEntry ? [exactEntry] : [];
  }
  const hierarchyTopicPhrases = [
    "تسمية يونانية قديمة",
    "النقوش المقدسة",
    "اسم الكتابة المقدسة",
    "24 قيمة أحادية الصامت",
    "كام علامة أحادية الصوت",
  ];
  if (hierarchyTopicPhrases.some((phrase) => query.includes(normalize(phrase)))) {
    const exactEntry = KNOWLEDGE.find((entry) => entry.id === "egyptian-hieroglyphic-basics");
    return exactEntry ? [exactEntry] : [];
  }

  const ranked = KNOWLEDGE.map((entry) => {
    let score = 0;
    for (const keyword of entry.keywords) {
      const normalizedKeyword = normalize(keyword);
      if (normalizedKeyword && query.includes(normalizedKeyword)) {
        const exactKeywordMatch = normalizedKeyword === query;
        score += exactKeywordMatch ? 20 : normalizedKeyword.includes(" ") ? 4 : 2;
      }
    }
    return { entry, score };
  })
    .filter((item) => item.score >= 2)
    .sort((a, b) => b.score - a.score)
    .slice(0, Math.max(1, Math.min(limit, 6)));

  return ranked.map(({ entry }) => entry);
}

export function getRelevantKnowledgeSources(
  messages: Array<{ role: "user" | "assistant"; content: string }>,
  limit = 4,
): Array<{ title: string; organization: string; url: string }> {
  return getRelevantKnowledgeAnswer(messages, limit).sources;
}

export function getRelevantKnowledgeAnswer(
  messages: Array<{ role: "user" | "assistant"; content: string }>,
  limit = 4,
): {
  content: string;
  directAnswer?: string;
  sources: Array<{ title: string; organization: string; url: string }>;
} {
  const entries = getRelevantEntries(messages, limit);
  const seen = new Set<string>();
  const sources = entries
    .flatMap((entry) => entry.sources ?? [])
    .filter((source) => {
      if (seen.has(source.url)) return false;
      seen.add(source.url);
      return true;
    });
  const latest = messages.filter((message) => message.role === "user").at(-1)?.content ?? "";
  const previous = messages.filter((message) => message.role === "user").at(-2)?.content ?? "";
  const directEntry =
    isSourceRequest(latest) || !isContextualFollowUp(latest, previous)
      ? entries.find((entry) => entry.directResponse)
      : undefined;

  return {
    content: entries.map((entry) => entry.content).join("\n\n"),
    ...(directEntry ? { directAnswer: directEntry.content } : {}),
    sources,
  };
}

export function retrieveRelevantKnowledge(
  messages: Array<{ role: "user" | "assistant"; content: string }>,
  language: string,
  limit = 4,
): string {
  const ranked = getRelevantEntries(messages, limit);
  if (!ranked.length) return "";

  const instruction =
    language === "ar"
      ? "دي معلومات مرجعية موثقة تساعدك لو مرتبطة بالسؤال. جاوب بالمصري الطبيعي وبأسلوب بسيط. التزم بما تقوله المراجع؛ ما تضيفش أسماء أو تواريخ أو تفاصيل غير موجودة فيها، وما تعتبرش كل جبانة منف هي سقارة."
      : "Use this sourced reference only when it directly helps answer the latest question. Answer in the user's language and do not add names, dates, or details absent from the source.";

  return [
    "RETRIEVED HERITAGE KNOWLEDGE (use as a sourced reference):",
    instruction,
    ...ranked.map(
      (entry) =>
        `[${entry.title}] ${entry.content}${
          entry.sources?.length
            ? `\nVerified sources: ${entry.sources.map((source) => `${source.organization}: ${source.title} — ${source.url}`).join("; ")}`
            : ""
        }`,
    ),
    "Distinguish evidence from hypotheses. For Egyptian heritage answers, do not present unsourced details as verified facts. If the references do not establish a requested detail, say that the available sources do not confirm it. Do not invent citations.",
  ].join("\n\n");
}

